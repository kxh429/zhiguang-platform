def seed_database():
    """初始化种子数据"""
    # 创建管理员账户
    if not User.query.filter_by(username="admin").first():
        admin = User(username="admin", email="admin@zhiguang.edu", is_admin=True)
        admin.set_password("admin123")
        db.session.add(admin)

    # 创建测评题目
    if AssessmentQuestion.query.count() == 0:
        order = 0
        for dim, questions in QUESTIONS.items():
            for q_text in questions:
                order += 1
                db.session.add(AssessmentQuestion(dimension=dim, question_text=q_text, order_num=order))

    # 创建训练模块
    if TrainingModule.query.count() == 0:
        for mod_data in TRAINING_MODULES:
            db.session.add(TrainingModule(**mod_data))

    db.session.commit()
